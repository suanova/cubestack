// jsdom does not implement matchMedia; theme-storage's prefers-color-scheme
// fallback reads it. Install a writable stub; tests reassign it per case.
Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
});
