package ipam

import (
	"context"
	"path/filepath"
	"testing"
	"time"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"k8s.io/client-go/kubernetes/scheme"
	"k8s.io/client-go/rest"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/envtest"
	logf "sigs.k8s.io/controller-runtime/pkg/log"
	"sigs.k8s.io/controller-runtime/pkg/log/zap"

	ipamv1alpha1 "github.com/suanova/cubestack/api/ipam/v1alpha1"
)

// This package is a suite of its own rather than a set of specs inside
// internal/controller: the IPAM controllers belong to a different API group, and
// keeping them here means their envtest installs neither the ai CRDs nor the
// gateway/vendor ones the rest of the operator needs.
//
// These tests use Ginkgo (BDD-style Go testing framework). Refer to
// http://onsi.github.io/ginkgo/ to learn more about Ginkgo.

var (
	ctx       context.Context
	cancel    context.CancelFunc
	testEnv   *envtest.Environment
	cfg       *rest.Config
	k8sClient client.Client
)

func TestControllers(t *testing.T) {
	RegisterFailHandler(Fail)

	RunSpecs(t, "IPAM Controller Suite")
}

var _ = BeforeSuite(func() {
	logf.SetLogger(zap.New(zap.WriteTo(GinkgoWriter), zap.UseDevMode(true)))

	ctx, cancel = context.WithCancel(context.Background())

	Expect(ipamv1alpha1.AddToScheme(scheme.Scheme)).To(Succeed())

	By("bootstrapping test environment")
	testEnv = &envtest.Environment{
		CRDDirectoryPaths: []string{
			filepath.Join("..", "..", "..", "config", "crd", "bases"),
			// A minimal CRD for Multus's NetworkAttachmentDefinition, which the claims
			// mint and the audit lists. The real one belongs to Multus and is not
			// vendored — see the comment in testdata/multus-crd/.
			filepath.Join("..", "..", "..", "testdata", "multus-crd"),
		},
		ErrorIfCRDPathMissing: true,
		// kube-apiserver 1.36 takes ~60s to exit on SIGTERM while informer
		// watches are active; raise envtest's default 20s stop timeout so
		// AfterSuite teardown succeeds.
		ControlPlaneStopTimeout: 120 * time.Second,
	}

	var err error
	cfg, err = testEnv.Start()
	Expect(err).NotTo(HaveOccurred())
	Expect(cfg).NotTo(BeNil())

	k8sClient, err = client.New(cfg, client.Options{Scheme: scheme.Scheme})
	Expect(err).NotTo(HaveOccurred())
	Expect(k8sClient).NotTo(BeNil())
})

var _ = AfterSuite(func() {
	By("tearing down the test environment")
	cancel()
	Expect(testEnv.Stop()).To(Succeed())
})
